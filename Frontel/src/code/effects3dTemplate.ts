/**
 * vantaBackground3DTemplate — source emitted into exported projects when a
 * scene node uses a vanta-family effect. Mirrors src/three/vantaBackground.ts
 * but self-contained (no editor imports) and excludes the module table for
 * effects the project doesn't use.
 */
export const VANTA_BG_3D_TEMPLATE = `import { useEffect, useRef, useState } from "react";

type VantaInstance = { destroy: () => void; setOptions?: (o: Record<string, unknown>) => void };
type VantaFactory = (o: Record<string, unknown>) => VantaInstance;

/**
 * VantaBackground3D — mounts a vanta.js effect (bundled three.js r134 / p5).
 * Generated by Frontel; loads the effect module dynamically so bundles stay
 * small and pages render even if the network module fails.
 */
export function VantaBackground3D({
  effect,
  options,
  className,
}: {
  effect: string;
  options: Record<string, unknown>;
  className?: string;
}) {
  const hostRef = useRef<HTMLDivElement>(null);
  const [failed, setFailed] = useState(false);
  const optionsKey = JSON.stringify(options);

  useEffect(() => {
    const host = hostRef.current;
    if (!host) return;
    let instance: VantaInstance | null = null;
    let disposed = false;

    (async () => {
      try {
        await import("vanta/vendor/three.r134.min.js");
        const THREE = (window as unknown as { THREE?: unknown }).THREE;
        if (!THREE) throw new Error("three missing");
        let p5: unknown;
        if (effect === "TOPOLOGY" || effect === "TRUNK") {
          await import("vanta/vendor/p5.min.js");
          p5 = (window as unknown as { p5?: unknown }).p5;
        }
        const mod = (await import(/* @vite-ignore */ ("vanta/dist/vanta." + effect.toLowerCase() + ".min.js"))) as { default: VantaFactory };
        if (disposed) return;
        instance = mod.default({
          el: host,
          THREE,
          ...(p5 ? { p5 } : {}),
          mouseControls: false,
          touchControls: false,
          gyroControls: false,
          minHeight: 200,
          minWidth: 200,
          ...options,
        });
      } catch {
        if (!disposed) setFailed(true);
      }
    })();

    return () => {
      disposed = true;
      try { instance?.destroy(); } catch { /* gone */ }
      host.querySelectorAll("canvas").forEach((c) => c.remove());
    };
  }, [effect, optionsKey]);

  return (
    <div
      ref={hostRef}
      className={className}
      style={{ position: "relative", width: "100%", height: "100%", overflow: "hidden", background: String(options.backgroundColor ?? "#0c0e13") }}
    >
      {failed && (
        <div style={{ position: "absolute", inset: 0, display: "grid", placeItems: "center", color: "#8b93a9", fontSize: 12 }}>
          3D effect unavailable
        </div>
      )}
    </div>
  );
}
`;

/**
 * shaderBackground3DTemplate — self-contained GLSL background runtime for
 * exported projects (shader-family effects and custom shader scenes).
 */
export const SHADER_BG_3D_TEMPLATE = `import { useEffect, useRef } from "react";

const VERT = \`attribute vec2 p; void main(){ gl_Position = vec4(p, 0.0, 1.0); }\`;

const HEAD = \`precision highp float;
uniform vec2 uRes; uniform float uTime; uniform vec2 uMouse;
uniform vec3 uColorA; uniform vec3 uColorB; uniform vec3 uColorC;
uniform float uSpeed; uniform float uZoom;
\`;

/** Compiles a user fragment body into a runnable program (adds the uniform head). */
function buildProgram(gl: WebGLRenderingContext, body: string): WebGLProgram | null {
  const compile = (type: number, src: string) => {
    const s = gl.createShader(type)!;
    gl.shaderSource(s, src);
    gl.compileShader(s);
    if (!gl.getShaderParameter(s, gl.COMPILE_STATUS)) { gl.deleteShader(s); return null; }
    return s;
  };
  const vs = compile(gl.VERTEX_SHADER, VERT);
  const fs = compile(gl.FRAGMENT_SHADER, HEAD + body);
  if (!vs || !fs) return null;
  const p = gl.createProgram()!;
  gl.attachShader(p, vs); gl.attachShader(p, fs); gl.linkProgram(p);
  return gl.getProgramParameter(p, gl.LINK_STATUS) ? p : null;
}

function hexToVec(hex: string): [number, number, number] {
  const c = (hex || "#888888").replace("#", "");
  const f = c.length === 3 ? c.split("").map((x) => x + x).join("") : c;
  const n = parseInt(f, 16) || 0x888888;
  return [((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255];
}

/**
 * ShaderBackground3D — fullscreen GLSL background. Generated by Frontel.
 * The body receives iTime, iResolution, iMouse, uColorA/B/C, uSpeed, uZoom.
 */
export function ShaderBackground3D({
  code,
  colorA = "#2dd4bf",
  colorB = "#0396ff",
  colorC = "#020014",
  speed = 1,
  zoom = 1,
  className,
}: {
  code: string;
  colorA?: string;
  colorB?: string;
  colorC?: string;
  speed?: number;
  zoom?: number;
  className?: string;
}) {
  const hostRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const host = hostRef.current;
    if (!host) return;
    const canvas = document.createElement("canvas");
    canvas.style.cssText = "position:absolute;inset:0;width:100%;height:100%;display:block;";
    const gl = canvas.getContext("webgl", { antialias: false, alpha: false });
    if (!gl) return;
    const prog = buildProgram(gl, code);
    if (!prog) return;
    gl.useProgram(prog);
    const buf = gl.createBuffer();
    gl.bindBuffer(gl.ARRAY_BUFFER, buf);
    gl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1, -1, 3, -1, -1, 3]), gl.STATIC_DRAW);
    const loc = gl.getAttribLocation(prog, "p");
    gl.enableVertexAttribArray(loc);
    gl.vertexAttribPointer(loc, 2, gl.FLOAT, false, 0, 0);
    const U = (n: string) => gl.getUniformLocation(prog, n);
    gl.uniform3fv(U("uColorA"), hexToVec(colorA));
    gl.uniform3fv(U("uColorB"), hexToVec(colorB));
    gl.uniform3fv(U("uColorC"), hexToVec(colorC));
    gl.uniform1f(U("uSpeed"), speed);
    gl.uniform1f(U("uZoom"), zoom);
    let raf = 0;
    let disposed = false;
    const start = performance.now();
    const reduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    const frame = () => {
      if (disposed) return;
      gl.uniform1f(U("uTime"), (performance.now() - start) / 1000);
      gl.uniform2f(U("uMouse"), 0.5, 0.5);
      gl.drawArrays(gl.TRIANGLES, 0, 3);
      if (!reduced) raf = requestAnimationFrame(frame);
    };
    const resize = () => {
      const w = host.clientWidth || 600, h = host.clientHeight || 400;
      canvas.width = w; canvas.height = h;
      gl.viewport(0, 0, w, h);
      gl.uniform2f(U("uRes"), w, h);
      frame();
    };
    resize();
    const ro = new ResizeObserver(resize);
    ro.observe(host);
    return () => {
      disposed = true;
      cancelAnimationFrame(raf);
      ro.disconnect();
      gl.deleteProgram(prog);
      canvas.remove();
    };
  }, [code, colorA, colorB, colorC, speed, zoom]);

  return <div ref={hostRef} className={className} style={{ position: "relative", width: "100%", height: "100%", overflow: "hidden" }} />;
}
`;

const HEX_TO_INT_HELPER = `function hexToInt(hex) {
  const c = (hex || "#000000").replace("#", "");
  const f = c.length === 3 ? c.split("").map((x) => x + x).join("") : c;
  return parseInt(f, 16) || 0;
}
`;

/**
 * Builds the options object literal (as source) for a vanta effect from
 * preset params: strings quoted, numbers/booleans raw, colors converted to
 * the int format vanta expects.
 */
export function vantaOptionsLiteral(
  params: Record<string, unknown> | undefined,
  intColorKeys: Set<string>,
): string {
  const entries = Object.entries(params ?? {}).map(([k, v]) => {
    if (intColorKeys.has(k) && typeof v === "string") return `${k}: 0x${v.replace("#", "").padStart(6, "0")}`;
    if (typeof v === "string") return `${k}: ${JSON.stringify(v)}`;
    return `${k}: ${String(v)}`;
  });
  return `{ ${entries.join(", ")} }`;
}

